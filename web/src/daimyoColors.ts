// 大名ごとの色
//
// 色は大名に固定で割り当てる（領地が増減しても、誰がプレイヤーでも同じ大名は同じ色）。
// 12色の割り当ては、ゲーム開始時に隣接している大名同士の色差（OKLab）が最大になるよう、
// 通常の色覚と色覚多様性（1型・2型）のシミュレーションの両方で探索して決めた。
// 近い色の大名が隣り合う場合に備え、地図上の国名・凡例・ホバー表示でも大名を判別できるようにしている。

/** 大名ID → 色 */
const DAIMYO_COLORS: Readonly<Record<number, string>> = {
  1: "#1b9e77", // 蛎崎
  2: "#7570b3", // 伊達
  3: "#d62728", // 上杉
  4: "#2a78d6", // 武田
  5: "#e6ab02", // 北条
  6: "#a6761d", // 徳川
  7: "#bcbd22", // 織田
  8: "#17becf", // 足利
  9: "#e7298a", // 毛利
  10: "#66a61e", // 長宗我部
  11: "#e8702a", // 大友
  12: "#b07aa1", // 島津
};

/** 未知の大名ID（マスターデータの追加など）に使う色 */
const FALLBACK_COLOR = "#8c8b84";

/** 大名の色を返す */
export function daimyoColor(daimyoId: number): string {
  return DAIMYO_COLORS[daimyoId] ?? FALLBACK_COLOR;
}
